/** @file request-stream.ts @description Assemble expected-free sandbox requests from verified spans. @module runner */
import { validateCompiledArtifact } from "@quorem/execution";
import { encodeJsonStringChunks } from "@quorem/questions";
import type { spoolInput } from "../checkpoints/input-spool.ts";
import { composedInput } from "../sandbox/input.ts";
import { caseSpans } from "./case-spans.ts";
import { metadataSpans } from "./metadata-spans.ts";
type Spool = Awaited<ReturnType<typeof spoolInput>>;
const encoder = new TextEncoder();
/** All inputs are digest-verified spools; generated bytes are hashed before sandbox execution. */
export async function streamedCaseRequest(options: {
  source: Spool;
  metadata: Spool;
  testcase: Spool;
  level: number | null;
  operation: "direct" | "compile-execute" | "execute";
  language: string;
  artifact?: string;
  signal?: AbortSignal;
}) {
  const testcase = await caseSpans(options.testcase),
    metadata = await metadataSpans(options.metadata, options.level);
  if (options.operation === "execute") {
    if (!options.artifact) throw new Error("Missing compiled artifact");
    validateCompiledArtifact(options.artifact, options.language);
  }
  async function* payload(): AsyncGenerator<Uint8Array> {
    yield encoder.encode("{");
    if (options.operation === "execute") {
      yield encoder.encode(`"artifact":${options.artifact},"operation":"execute",`);
    } else {
      if (options.operation === "compile-execute")
        yield encoder.encode('"operation":"compile-execute",');
      yield encoder.encode('"source":');
      yield* encodeJsonStringChunks(options.source.stream());
      yield encoder.encode(',"signature":');
      for await (const part of options.metadata.stream(
        metadata.signature.start,
        metadata.signature.length,
      ))
        yield part as Uint8Array;
      yield encoder.encode(',"methods":{');
      for (let i = 0; i < metadata.methods.length; i++) {
        if (i) yield encoder.encode(",");
        yield encoder.encode(`${JSON.stringify(metadata.methods[i].name)}:`);
        const span = metadata.methods[i].span;
        for await (const part of options.metadata.stream(span.start, span.length))
          yield part as Uint8Array;
      }
      yield encoder.encode("},");
      if (options.operation === "direct") {
        yield encoder.encode('"sql":');
        if (metadata.sql)
          for await (const part of options.metadata.stream(metadata.sql.start, metadata.sql.length))
            yield part as Uint8Array;
        else yield encoder.encode("null");
        yield encoder.encode(",");
      }
    }
    yield encoder.encode('"args":');
    yield* testcase.args();
    yield encoder.encode(',"calls":');
    yield* testcase.requestCalls();
    yield encoder.encode("}");
  }
  return { input: await composedInput(payload, options.signal), testcase, metadata };
}
